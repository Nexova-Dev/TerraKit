#: Key id of the committed development keypair. `tools/build_registry.py --production` refuses to
#: publish anything signed with it.
DEV_KEY_ID = "terrakit-dev-2026"


#: File extension per compression method.
#:
#: One table, used by both the writer and the verifier. An earlier version derived the name
#: independently in each place — the writer produced `data.sqlite.zst` while the verifier looked
#: for `data.sqlite.zstd` — so every publish failed its own verification with "missing compressed
#: artifact". The self-check worked; what it caught was that the two sites had drifted apart.
#:
#: `.zst` rather than `.zstd`: it is what the `zstd` CLI appends by default, it is shorter, and it
#: is what PACKAGE_FORMAT.md §6 specifies.
COMPRESSION_EXTENSIONS: dict[str, str] = {
    "zstd": ".zst",
    "gzip": ".gz",
}


def compressed_filename(path: str, compression: str | None) -> str | None:
    """The on-disk name of a compressed artifact, or None when uncompressed."""
    if not compression:
        return None
    extension = COMPRESSION_EXTENSIONS.get(compression)
    if extension is None:
        raise ValueError(
            f"unknown compression method {compression!r}; "
            f"known methods are {sorted(COMPRESSION_EXTENSIONS)}"
        )
    return f"{path}{extension}"


def zstd_available() -> bool:
    """Whether a zstd implementation is reachable.

    Checked rather than assumed: the pipeline shells out to `zstd` in preference to a Python
    binding, because the CLI decompresses with libzstd and the two must agree exactly on the
    format. If neither is present the caller is told plainly instead of producing an
    uncompressed artifact that the manifest then misdescribes.
    """
    if shutil.which("zstd"):
        return True
    try:
        import zstandard  # noqa: F401

        return True
    except ImportError:
        return False


@dataclass
class CompressionResult:
    compressed_path: Path
    raw_size: int
    compressed_size: int
    method: str
    level: int

    @property
    def ratio(self) -> float:
        if self.compressed_size == 0:
            return 0.0
        return self.raw_size / self.compressed_size


@dataclass
class SignatureResult:
    key_id: str
    signature_hex: str
    public_key_hex: str
    algorithm: str = "ed25519"


def compress_database(
    database_path: Path,
    output_path: Path,
    *,
    level: int = 19,
) -> CompressionResult:
    """
    Compress `data.sqlite` with zstd.

    Level 19 and the parameters chosen in `PACKAGE_FORMAT.md` §6. `no dictionary` matters:
    dictionary compression would make each package decompressible only alongside its siblings,
    which conflicts with `terrakit install github.com/...` for a single package.

    Prefers the `zstd` CLI because the CLI decompresses with libzstd and a divergence between the
    two implementations would surface as a corrupt install rather than as a build error. Falls back
    to the `zstandard` module when the binary is absent.
    """
    raw_size = database_path.stat().st_size

    if shutil.which("zstd"):
        # --long=30 improves the ratio on large SQLite files, which is where it matters.
        subprocess.run(
            ["zstd", f"-{level}", "--long=30", "-q", "-f", "-o",
             str(output_path), str(database_path)],
            check=True,
        )
        method = "zstd"
    else:
        try:
            import zstandard
        except ImportError as exc:  # pragma: no cover - guarded by zstd_available()
            raise RuntimeError(
                "no zstd implementation found. Install the `zstd` binary or the "
                "`zstandard` Python module."
            ) from exc
        compressor = zstandard.ZstdCompressor(level=level, write_checksum=True)
        with database_path.open("rb") as src, output_path.open("wb") as dst:
            compressor.copy_stream(src, dst)
        method = "zstd"

    return CompressionResult(
        compressed_path=output_path,
        raw_size=raw_size,
        compressed_size=output_path.stat().st_size,
        method=method,
        level=level,
    )


def read_public_key(private_key_path: Path) -> str:
    """Hex-encoded 32-byte Ed25519 public key for a private key file."""
    from cryptography.hazmat.primitives import serialization

    key = serialization.load_pem_private_key(
        private_key_path.read_bytes(), password=None
    )
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    if not isinstance(key, Ed25519PrivateKey):
        raise ValueError(f"{private_key_path} is not an Ed25519 private key")
    public = key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )
    return public.hex()


def sign_manifest(
    manifest_path: Path,
    output_path: Path,
    private_key_path: Path,
    *,
    key_id: str,
) -> SignatureResult:
    """
    Sign the canonical manifest bytes.

    The signature covers the file's **bytes**, not a parsed and re-serialized object. This is not a
    detail: signing a parsed object means the signer and the verifier can disagree about what the
    document says — different key ordering, different number formatting, a duplicate key — and a
    manifest that verifies against one implementation can fail against another. Signing bytes has
    exactly one interpretation. See `SECURITY.md` §3.

    The manifest is written with sorted keys and a fixed separator so that a rebuild produces
    byte-identical output, which is what makes the signature reproducible.
    """
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    key = serialization.load_pem_private_key(
        private_key_path.read_bytes(), password=None
    )
    if not isinstance(key, Ed25519PrivateKey):
        raise ValueError(f"{private_key_path} is not an Ed25519 private key")

    payload = manifest_path.read_bytes()
    signature = key.sign(payload)

    document = {
        "algorithm": "ed25519",
        "keyId": key_id,
        "publicKey": read_public_key(private_key_path),
        "signature": signature.hex(),
        "signedContent": manifest_path.name,
        "algorithmVersion": 1,
    }
    output_path.write_text(
        json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    return SignatureResult(
        key_id=key_id,
        signature_hex=signature.hex(),
        public_key_hex=document["publicKey"],
    )


def canonical_manifest_bytes(manifest: dict) -> bytes:
    """
    Serialize a manifest the way the pipeline writes it.

    Shared by `finalize_release` and by anything that needs to re-derive the signed bytes, so the
    two can never disagree about the encoding.
    """
    return (
        json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    ).encode("utf-8")


def finalize_release(
    package_dir: Path,
    *,
    compress: bool = True,
    sign_key: Path | None = None,
    key_id: str | None = None,
    log=print,
) -> dict:
    """
    Turn a build into a publishable release: compress, checksum, sign.

    Returns a summary dict. The manifest is rewritten *before* signing, so the signature always
    covers the bytes that were actually written — the failure mode being avoided is a manifest
    whose recorded `compressedSize` was added after signing, leaving a signature that verifies over
    stale content.
    """
    database = package_dir / "data.sqlite"
    manifest_path = package_dir / "manifest.json"
    signature_path = package_dir / "signature.json"

    if not database.is_file():
        raise FileNotFoundError(f"{database} does not exist")
    if not manifest_path.is_file():
        raise FileNotFoundError(f"{manifest_path} does not exist")

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    files = manifest.get("files", [])
    for entry in files:
        if entry.get("path") == "data.sqlite":
            db_entry = entry
            break
    else:
        raise ValueError("manifest has no data.sqlite entry in files[]")

    if compress:
        artifact_name = compressed_filename("data.sqlite", "zstd")
        assert artifact_name is not None
        compressed_path = package_dir / artifact_name
        result = compress_database(database, compressed_path)
        log(
            f"    compressed {result.raw_size:,} -> {result.compressed_size:,} bytes "
            f"({result.ratio:.1f}x, zstd -{result.level})"
        )
        db_entry["compression"] = "zstd"
        db_entry["compressedSize"] = result.compressed_size
        # The download artifact carries a different digest from the extracted file,
        # and the installer verifies BOTH: the compressed bytes before decompressing
        # and the extracted bytes after. Verifying only one leaves a decompression bug
        # able to write whatever it likes to disk.
        db_entry["compressedSha256"] = _sha256(compressed_path)
    else:
        db_entry["compression"] = None
        db_entry["compressedSize"] = None
        db_entry["compressedSha256"] = None
        log("    compression skipped (--no-compress)")

    # packageSha256 is the digest of data.sqlite as installed. Recomputed rather
    # than trusted, so a build whose manifest drifted from its database is caught
    # here instead of by a user.
    db_entry["sha256"] = _sha256(database)
    db_entry["rawSize"] = database.stat().st_size
    manifest["packageSha256"] = db_entry["sha256"]
    manifest["size"] = {
        "raw": db_entry["rawSize"],
        "compressed": db_entry["compressedSize"],
    }

    manifest_path.write_bytes(canonical_manifest_bytes(manifest))
    log(f"    manifest updated, packageSha256={manifest['packageSha256'][:12]}")

    if sign_key is not None:
        if key_id is None:
            raise ValueError("--sign-key requires --sign-key-id")
        if not sign_key.is_file():
            raise FileNotFoundError(
                f"{sign_key} does not exist. Generate a development keypair with "
                "tools/generate_dev_key.py, or point at the release key."
            )
        signature = sign_manifest(manifest_path, signature_path, sign_key, key_id=key_id)
        log(f"    signed with ed25519, keyId={signature.key_id}")

    return {
        "package": package_dir.name,
        "manifest": manifest,
        "signed": sign_key is not None,
        "key_id": key_id if sign_key is not None else None,
    }


def _sha256(path: Path) -> str:
    import hashlib

    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verify_release(package_dir: Path) -> tuple[bool, list[str]]:
    """
    Independently check a release directory: manifest digests, then signature.

    The same checks the CLI performs, in the same order, so `publish --dry-run` and `terrakit add`
    agree. A publisher tool that verifies differently from the installer is a publisher tool that
    ships corrupt packages.
    """
    problems: list[str] = []
    manifest_path = package_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    for entry in manifest.get("files", []):
        path = package_dir / entry["path"]
        if not path.is_file():
            problems.append(f"missing file {entry['path']}")
            continue
        actual = _sha256(path)
        if actual != entry.get("sha256"):
            problems.append(
                f"{entry['path']}: sha256 {actual[:12]} != manifest {str(entry.get('sha256'))[:12]}"
            )
        try:
            compressed_name = compressed_filename(
                entry["path"], entry.get("compression")
            )
        except ValueError as exc:
            problems.append(f"{entry['path']}: {exc}")
            continue
        if compressed_name:
            compressed = package_dir / compressed_name
            if not compressed.is_file():
                problems.append(f"missing compressed artifact {compressed_name}")
            elif entry.get("compressedSha256"):
                actual_c = _sha256(compressed)
                if actual_c != entry["compressedSha256"]:
                    problems.append(
                        f"{compressed_name}: sha256 {actual_c[:12]} != "
                        f"manifest {entry['compressedSha256'][:12]}"
                    )

    signature_path = package_dir / "signature.json"
    if signature_path.is_file():
        from cryptography.hazmat.primitives.asymmetric.ed25519 import (
            Ed25519PublicKey,
        )
        from cryptography.exceptions import InvalidSignature

        document = json.loads(signature_path.read_text(encoding="utf-8"))
        if document.get("algorithm") != "ed25519":
            problems.append(f"unsupported signature algorithm {document.get('algorithm')}")
        else:
            try:
                public = Ed25519PublicKey.from_public_bytes(
                    bytes.fromhex(document["publicKey"])
                )
                public.verify(
                    bytes.fromhex(document["signature"]),
                    manifest_path.read_bytes(),
                )
            except (InvalidSignature, ValueError, KeyError) as exc:
                problems.append(f"signature does not verify: {exc}")
    else:
        problems.append("no signature.json")

    return (not problems), problems
